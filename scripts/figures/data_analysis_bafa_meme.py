def extract_coefficients_robust(content):
    """Robust extraction of coefficients from the table"""
    lines = content.split('\n')

    # Find the header line with Coef. (case insensitive)
    header_line = -1
    for i, line in enumerate(lines):
        if 'coef.' in line.lower() and 'std.err' in line.lower():
            header_line = i
            break

    if header_line == -1:
        return []

    results = []

    # Start from the line after header (skip the separator line)
    start_line = header_line + 2
    if start_line >= len(lines):
        return []

    # Process each line
    for i in range(start_line, len(lines)):
        line = lines[i]

        # Stop conditions
        if line.strip().startswith('=') or line.strip().startswith('-'):
            break
        if 'Var' in line and not any(c.isalpha() for c in line[:10]):
            break
        if not line.strip():
            continue

        # Split the line
        parts = line.split()
        if len(parts) < 6:
            continue

        # Find where the numbers start (first part that looks like a number with decimal)
        num_start = -1
        for idx, part in enumerate(parts):
            if re.match(r'^-?\d+\.\d+$', part):
                num_start = idx
                break

        if num_start == -1:
            continue

        # Variable name is everything before num_start
        var_name = ' '.join(parts[:num_start])

        # Extract the numbers (coefficient, std err, z, p-value)
        try:
            coef = float(parts[num_start])
            std_err = float(parts[num_start + 1])
            z = float(parts[num_start + 2])
            p_value = float(parts[num_start + 3])

            # Significance stars
            sig = ''
            if p_value < 0.001:
                sig = '***'
            elif p_value < 0.01:
                sig = '**'
            elif p_value < 0.05:
                sig = '*'

            results.append({
                'Variable': var_name,
                'Coefficient': coef,
                'Std_Error': std_err,
                'Z_value': z,
                'P_value': p_value,
                'Significance': sig
            })
        except (ValueError, IndexError) as e:
            continue

    return results

