# Helper function to get sorted legend handles and labels
# =============================================================================
def get_sorted_legend(ax, models_plotted):
    """
    Get legend handles and labels sorted alphabetically by model name.
    """
    # Get current handles and labels from the plot
    handles, labels = ax.get_legend_handles_labels()

    # Create a list of tuples (label, handle) and sort by label
    label_handle_pairs = list(zip(labels, handles))

    # Filter only the models that were actually plotted
    label_handle_pairs = [(label, handle) for label, handle in label_handle_pairs
                          if label in models_plotted]

    # Sort alphabetically by label
    label_handle_pairs.sort(key=lambda x: x[0])

    # Unzip back to handles and labels
    sorted_labels, sorted_handles = zip(*label_handle_pairs) if label_handle_pairs else ([], [])

    return sorted_handles, sorted_labels

