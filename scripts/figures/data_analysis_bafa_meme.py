def clean_coefficient_label(term, grouped_modal_map=None):
    """
    Convert statsmodels/patsy style coefficient names into readable labels.

    Examples of input:
      - "Intercept" -> "Intercept"
      - "C(ethnicity_grouped)[T.1]" -> "ethnicity_grouped = Other (vs reference)"
      - "ethnicity[T.White]" -> "ethnicity = White (vs reference)"
      - "initial_belief_normalized_centered" -> "Initial Belief"
      - "C(stance_direction)[T.Against]" -> "stance_direction = Against (vs Pro)"

    Parameters
    - term: string (coefficient name)
    - grouped_modal_map: optional dict mapping grouped var name -> modal_label
        e.g. {'ethnicity_grouped': 'White', 'country_grouped': 'Great Britain'}
        If provided and term is something like C(var)[T.1] we will use modal_label
        to show "(vs <modal_label>)". If not provided, we show "(vs reference)".

    Returns:
    - readable_label (string)
    """
    # Keep intercept as-is
    if term == 'Intercept':
        return 'Intercept'

    # Short-cuts for common patterns
    if 'initial_belief' in term.lower():
        return 'Initial Belief'

    # Pattern: C(var)[T.level] or var[T.level]
    # Examples:
    #   C(ethnicity_grouped)[T.1]
    #   ethnicity[T.White]
    pat = re.compile(r'^(?:C\()?([^\)\[]+)(?:\))?(?:\[(?:T\.)?(.+?)\])?$')
    m = pat.match(term)
    if not m:
        # fallback minimal formatting
        return term.replace('_centered', '').replace('C(', '').replace(')', '')

    var = m.group(1)
    level = m.group(2)

    # If there's no level (e.g., numeric predictor), return cleaned var
    if level is None:
        return var.replace('_centered', '')

    # If level looks like "0" or "1" or ".0" (common for grouped 0/1)
    # map T.0 => reference/modal, T.1 => Other
    # Use grouped_modal_map if provided to fill in modal label
    level_str = level.strip()

    # Handle levels that are numeric like '0' or '1'
    if re.fullmatch(r'\.?\d+', level_str):
        # numeric level (e.g., "0", "1", ".0")
        if level_str.endswith('.0'):
            level_str = level_str[:-2]
        # interpret 0 as reference/modal
        if level_str == '0':
            # If grouped_modal_map has var, use that as the reference label
            if grouped_modal_map and var in grouped_modal_map:
                ref_label = grouped_modal_map[var]
                return f"{var} = {ref_label} (reference)"
            else:
                return f"{var} = Reference"
        else:
            # treat as "Other" for 1 (or any non-zero)
            if grouped_modal_map and var in grouped_modal_map:
                ref_label = grouped_modal_map[var]
                return f"{var} = Other (vs {ref_label})"
            else:
                return f"{var} = Other (vs reference)"

    # For textual level names (e.g., "White", "Male", "Against")
    level_display = level_str
    # Show "var = level (vs reference/modal)" - fill modal if available
    if grouped_modal_map and var in grouped_modal_map:
        ref_label = grouped_modal_map[var]
        return f"{var} = {level_display} (vs {ref_label})"
    else:
        return f"{var} = {level_display} (vs reference)"

