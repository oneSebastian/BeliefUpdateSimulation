# Prepare data: keep predictors where at least one model has |z| > threshold
# with cleaned labels (EXACTLY AS IN ORIGINAL CODE)
# =============================================================================
def prepare_data_for_plotting(df, threshold=2.0, grouped_modal_map=None):
    # Drop intercept
    df = df[df['Variable'] != 'Intercept'].copy()

    # Identify variables with at least one |z| > threshold across any model
    mask = (
        df.groupby('Variable')['Z_value']
          .transform(lambda s: (s.abs() > threshold).any())
          .astype(bool)
    )
    df_filt = df[mask].copy()

    models = df_filt['Model'].unique().tolist()

    # Pivot: variables as rows, models as columns, z-scores as values
    z_pivot = df_filt.pivot_table(index='Variable', columns='Model', values='Z_value', aggfunc='first')

    # Clean row labels using clean_coefficient_label and wrap long text
    cleaned_index = []
    for raw in z_pivot.index:
        try:
            cleaned = clean_coefficient_label(raw, grouped_modal_map=grouped_modal_map)
            if not cleaned:
                cleaned = format_predictor_name_simple(raw)
            # Wrap long labels to multiple lines
            cleaned = wrap_text(cleaned, max_length=40)
        except Exception:
            cleaned = format_predictor_name_simple(raw)
            cleaned = wrap_text(cleaned, max_length=40)
        cleaned_index.append(cleaned)

    z_pivot.index = cleaned_index
    z_pivot = z_pivot.sort_index()

    return z_pivot, models

# =============================================================================
# Helper function to get sorted legend handles and labels (including z-score line)
# =============================================================================
def get_sorted_legend(ax, models_plotted, threshold):
    """
    Get legend handles and labels sorted alphabetically by model name.
    Includes the z-score reference line in the legend.
    """
    # Get current handles and labels from the plot
    handles, labels = ax.get_legend_handles_labels()

    # Create a list of tuples (label, handle) for model labels
    model_pairs = [(label, handle) for label, handle in zip(labels, handles)
                   if label in models_plotted]

    # Sort model pairs alphabetically by label
    model_pairs.sort(key=lambda x: x[0])

    # Separate model handles and labels
    sorted_handles = [handle for label, handle in model_pairs]
    sorted_labels = [label for label, handle in model_pairs]

    # Add the z-score reference line back
    for label, handle in zip(labels, handles):
        if label == f'|z|={threshold}' or '|z|=' in label:
            # Add it at the end
            sorted_handles.append(handle)
            sorted_labels.append(label)
            break

    return sorted_handles, sorted_labels

