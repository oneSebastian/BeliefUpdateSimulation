# Helper function to wrap long text labels
# =============================================================================
def wrap_text(text, max_length=40):
    """Wrap text to multiple lines if it exceeds max_length."""
    words = text.split()
    lines = []
    current_line = []
    current_length = 0

    for word in words:
        if current_length + len(word) + (1 if current_line else 0) <= max_length:
            current_line.append(word)
            current_length += len(word) + (1 if current_line else 0)
        else:
            if current_line:
                lines.append(' '.join(current_line))
            current_line = [word]
            current_length = len(word)

    if current_line:
        lines.append(' '.join(current_line))

    return '\n'.join(lines)

# =============================================================================
# Custom square-root scale (equidistant square intervals), domain [-81, 16]
# =============================================================================
def set_square_interval_scale(ax, min_val=-81, max_val=16, minor_subdivisions=0, show_minor=False):
    """
    Signed square-root axis with equal visual spacing between consecutive squares.
    Forward:  f(x) = sign(x) * sqrt(|x|)
    Inverse:  f^{-1}(y) = sign(y) * (|y|**2)
    """
    def fwd(x):
        x = np.asarray(x, dtype=float)
        return np.sign(x) * np.sqrt(np.abs(x))

    def inv(y):
        y = np.asarray(y, dtype=float)
        return np.sign(y) * (np.abs(y) ** 2)

    ax.set_xscale('function', functions=(fwd, inv))

    n_neg = int(np.floor(np.sqrt(abs(min_val)))) if min_val < 0 else 0
    n_pos = int(np.floor(np.sqrt(max_val))) if max_val > 0 else 0

    neg_sq = [-(n*n) for n in range(n_neg, 0, -1)]
    pos_sq = [n*n for n in range(0, n_pos + 1)]
    major_vals = [v for v in (neg_sq + pos_sq) if (v >= min_val and v <= max_val)]

    ax.set_xticks(major_vals)
    ax.set_xticklabels([str(v) for v in major_vals])

    if minor_subdivisions > 0 and show_minor:
        minor_vals = []
        for n in range(0, n_neg):
            mids = np.linspace(n, n+1, minor_subdivisions + 1)[1:-1]
            vals = [-(m*m) for m in mids]
            minor_vals.extend([v for v in vals if (v >= min_val and v <= max_val)])
        for n in range(0, n_pos):
            mids = np.linspace(n, n+1, minor_subdivisions + 1)[1:-1]
            vals = [(m*m) for m in mids]
            minor_vals.extend([v for v in vals if (v >= min_val and v <= max_val)])
        ax.set_xticks(minor_vals, minor=True)
    else:
        ax.xaxis.set_minor_locator(mticker.NullLocator())

    ax.set_xlim(min_val, max_val)

# =============================================================================
# Symmetric log scale from -100 to 100 (10^2 to -10^2)
# =============================================================================
def set_symmetric_log_scale(ax, min_val=-100, max_val=100):
    """
    Symmetric log scale from -100 to 100 using sign(x) * log10(|x| + 1).
    """
    def fwd(x):
        x = np.asarray(x, dtype=float)
        return np.sign(x) * np.log10(np.abs(x) + 1)

    def inv(y):
        y = np.asarray(y, dtype=float)
        return np.sign(y) * (10 ** np.abs(y) - 1)

    ax.set_xscale('function', functions=(fwd, inv))

    major_ticks = [-100, -10, -1, 0, 1, 10, 100]
    major_ticks = [t for t in major_ticks if t >= min_val and t <= max_val]

    ax.set_xticks(major_ticks)
    ax.set_xticklabels([str(t) for t in major_ticks])

    minor_ticks = []
    for n in range(-90, -9, 10):
        if n >= min_val:
            minor_ticks.append(n)
    for n in range(-9, 0):
        if n >= min_val and n not in major_ticks:
            minor_ticks.append(n)
    for n in range(2, 10):
        if n <= max_val and n not in major_ticks:
            minor_ticks.append(n)
    for n in range(20, 100, 10):
        if n <= max_val and n not in major_ticks:
            minor_ticks.append(n)

    if minor_ticks:
        ax.set_xticks(minor_ticks, minor=True)
    else:
        ax.xaxis.set_minor_locator(mticker.NullLocator())

    ax.set_xlim(min_val, max_val)

