def set_square_interval_scale(ax, min_val=-81, max_val=16, minor_subdivisions=0, show_minor=False):
    def fwd(x):
        x = np.asarray(x, dtype=float)
        return np.sign(x) * np.sqrt(np.abs(x))
    def inv(y):
        y = np.asarray(y, dtype=float)
        return np.sign(y) * (np.abs(y) ** 2)
    ax.set_xscale('function', functions=(fwd, inv))
    n_neg = int(np.floor(np.sqrt(abs(min_val)))) if min_val < 0 else 0
    n_pos = int(np.floor(np.sqrt(max_val))) if max_val > 0 else 0
    neg_sq = [-(n * n) for n in range(n_neg, 0, -1)]
    pos_sq = [n * n for n in range(0, n_pos + 1)]
    major_vals = [v for v in (neg_sq + pos_sq) if (v >= min_val and v <= max_val)]
    ax.set_xticks(major_vals)
    ax.set_xticklabels([str(v) for v in major_vals])
    if minor_subdivisions > 0 and show_minor:
        minor_vals = []
        for n in range(0, n_neg):
            mids = np.linspace(n, n + 1, minor_subdivisions + 1)[1:-1]
            vals = [-(m * m) for m in mids]
            minor_vals.extend([v for v in vals if (v >= min_val and v <= max_val)])
        for n in range(0, n_pos):
            mids = np.linspace(n, n + 1, minor_subdivisions + 1)[1:-1]
            vals = [(m * m) for m in mids]
            minor_vals.extend([v for v in vals if (v >= min_val and v <= max_val)])
        ax.set_xticks(minor_vals, minor=True)
    else:
        ax.xaxis.set_minor_locator(mticker.NullLocator())
    ax.set_xlim(min_val, max_val)

