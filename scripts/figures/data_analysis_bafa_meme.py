def make_grouped_binary(series, threshold=0.80):
    """Return (grouped_series, dominant_value or None, meets_threshold_bool)."""
    if series.dropna().empty:
        return pd.Series(index=series.index, dtype=object), None, False
    counts = series.value_counts(dropna=True)
    modal = counts.idxmax()
    p_modal = counts.max() / counts.sum()
    if p_modal >= threshold:
        # 0 -> dominant (reference), 1 -> Other
        grouped = series.map(lambda x: 0 if x == modal else (1 if pd.notnull(x) else np.nan))
        return grouped, modal, True
    else:
        return pd.Series(index=series.index, dtype=object), modal, False

