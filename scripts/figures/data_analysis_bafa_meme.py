def prepare_data_for_plotting(df, threshold=2.0):
    # Drop intercept
    df = df[df['Variable'] != 'Intercept'].copy()

    # Identify variables with at least one |z| > threshold across any model
    mask = (
        df.groupby('Variable')['Z_value']
          .transform(lambda s: (s.abs() > threshold).any())
          .astype(bool)
    )
    df_filt = df[mask].copy()

    models = df_filt['Model'].unique().tolist()

    # Pivot: variables as rows, models as columns, z-scores as values
    z_pivot = df_filt.pivot_table(index='Variable', columns='Model', values='Z_value', aggfunc='first')

    # Format predictor names and sort
    z_pivot.index = [format_predictor_name(v) for v in z_pivot.index]
    z_pivot = z_pivot.sort_index()

    return z_pivot, models

