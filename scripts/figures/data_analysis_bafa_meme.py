def create_zscore_plot_square(z_df, models, threshold=2.0, min_val=-81, max_val=16):
    if z_df is None or z_df.empty:
        print("No predictors met the selection criterion.")
        return None

    # Increased height for multi-line labels and more spacing between predictors
    fig_h = max(12, len(z_df) * 0.65)
    fig, ax = plt.subplots(figsize=(5, fig_h))

    predictors = z_df.index[::-1]
    y_positions = np.arange(len(predictors))

    # Keep track of which models are actually plotted for legend
    plotted_models = set()

    for model in models:
        if model not in z_df.columns:
            continue
        vals = z_df[model].values[::-1]
        name = model_name_mapping.get(model, model)
        color = model_colors.get(name, '#333333')
        marker = human_marker if name == 'Human' else default_marker
        size = 130 if name == 'Human' else 110
        plotted_models.add(name)

        ax.scatter(
            vals, y_positions,
            label=name, color=color, marker=marker,
            s=size, alpha=0.9, edgecolors='white', linewidth=1.2, zorder=3
        )

    # Reference lines/band (DATA coordinates)
    ax.axvline(0, color='black', linewidth=1.5, zorder=1)
    ax.axvline(threshold, color='red', linestyle='--', linewidth=1.5, label=f'|z|={threshold}', zorder=1)
    ax.axvline(-threshold, color='red', linestyle='--', linewidth=1.5, zorder=1)
    ax.axvspan(-threshold, threshold, alpha=0.08, color='gray', zorder=0)

    # Apply square-interval scale and exact limits [-81, 16]
    set_square_interval_scale(ax, min_val=min_val, max_val=max_val, minor_subdivisions=0, show_minor=False)

    # Labels, grid, legend
    ax.set_yticks(y_positions)
    ax.set_yticklabels(predictors, fontsize=11.25)
    ax.set_xlabel('z-score', fontsize=12.5)
    ax.set_ylabel('Predictor', fontsize=12.5)

    ax.grid(True, axis='x', which='major', alpha=0.35, linestyle='-', linewidth=0.6)
    ax.set_axisbelow(True)

    # Get sorted legend handles and labels (models only, excluding threshold line)
    sorted_handles, sorted_labels = get_sorted_legend(ax, plotted_models)

    # Legend moved inside bottom left, single column, narrower, alphabetically sorted
    legend = ax.legend(
        sorted_handles, sorted_labels,
        loc='lower left',
        bbox_to_anchor=(0.02, 0.02),
        frameon=True,
        fontsize=9,
        framealpha=0.9,
        title='Models',
        title_fontsize=12.5,
        ncol=1,
        handleheight=1.5,
        handletextpad=0.5,
        borderpad=0.8,
        labelspacing=0.8,
        columnspacing=0.5
    )

    legend.get_frame().set_linewidth(0.5)
    legend.get_frame().set_boxstyle('square', pad=0.5)

    plt.tight_layout()
    plt.subplots_adjust(left=0.5, right=0.92, bottom=0.08, top=0.95)
    return fig

