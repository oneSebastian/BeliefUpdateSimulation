def format_predictor_name_simple(var_name):
    if 'Penalty' in var_name:
        return 'Topic: Penalty (vs UBI)'
    if 'Weight Loss' in var_name:
        return 'Topic: Weight Loss (vs UBI)'
    if 'initial_belief' in var_name.lower():
        return 'Initial Belief'
    return var_name.replace('_centered', '').replace('C(', '').replace(')', '')

# =============================================================================
# Prepare data: keep predictors where at least one model has |z| > threshold
# with cleaned labels
# =============================================================================
def prepare_data_for_plotting(df, threshold=2.0, grouped_modal_map=None):
    # Drop intercept
    df = df[df['Variable'] != 'Intercept'].copy()

    # Identify variables with at least one |z| > threshold across any model
    mask = (
        df.groupby('Variable')['Z_value']
          .transform(lambda s: (s.abs() > threshold).any())
          .astype(bool)
    )
    df_filt = df[mask].copy()

    models = df_filt['Model'].unique().tolist()

    # Pivot: variables as rows, models as columns, z-scores as values
    z_pivot = df_filt.pivot_table(index='Variable', columns='Model', values='Z_value', aggfunc='first')

    # Clean row labels using clean_coefficient_label and wrap long text
    cleaned_index = []
    for raw in z_pivot.index:
        try:
            cleaned = clean_coefficient_label(raw, grouped_modal_map=grouped_modal_map)
            if not cleaned:
                cleaned = format_predictor_name_simple(raw)
            # Wrap long labels to multiple lines
            cleaned = wrap_text(cleaned, max_length=40)
        except Exception:
            cleaned = format_predictor_name_simple(raw)
            cleaned = wrap_text(cleaned, max_length=40)
        cleaned_index.append(cleaned)

    z_pivot.index = cleaned_index
    z_pivot = z_pivot.sort_index()

    return z_pivot, models

