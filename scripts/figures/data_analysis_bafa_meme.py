def run_model(target_var, output_filename, model_description):
    """Run mixed linear model for a given target variable without grouping categories"""

    print(f"\n{'='*80}")
    print(f"RUNNING MODEL: {model_description}")
    print(f"Target: {target_var}")
    print(f"{'='*80}")

    # Prepare modeling dataframe
    model_cols = [target_var, "topic", "stance_direction", "persona_id"] + \
                 demographic_vars + [f"{v}_centered" for v in continuous_vars if f"{v}_centered" in df.columns]

    model_df = df[model_cols].dropna()

    # NO GROUPING - Keep all original categories
    # Categorical Config - set reference categories
    categorical_config = {
        "topic": {"ref": "UBI"},
        "stance_direction": {"ref": "Pro"},
        "gender": {"ref": "Female"},
        "ethnicity": {"ref": "White"},
        "country_of_birth": {"ref": "Great Britain"},
        "student_status": {"ref": "Not currently a student"},
        "employment_status": {"ref": "Employed full-time"},
        "highest_qualification": {"ref": "Bachelor's degree"}
    }

    # Apply categorical transformations without any grouping
    for col, config in categorical_config.items():
        if col in model_df.columns:
            ref_value = config["ref"]

            # Convert to categorical but don't group anything
            model_df[col] = model_df[col].astype('category').cat.remove_unused_categories()

            # Reorder categories so reference is first
            if ref_value in model_df[col].cat.categories:
                current_categories = model_df[col].cat.categories.tolist()
                new_order = [ref_value] + [c for c in current_categories if c != ref_value]
                model_df[col] = model_df[col].cat.reorder_categories(new_order, ordered=True)
            else:
                print(f"  Warning: Reference category '{ref_value}' not found in {col}")

    # Prepare predictors - include ALL categorical variables without grouping
    personality_vars = [f"{v}_centered" for v in continuous_vars if "BIG5" in v]
    demographic_categoricals = demographic_vars  # Keep all demographic variables as is

    predictors = ["C(topic)", "C(stance_direction)", "initial_belief_normalized_centered",
                  "age_centered", "familiarity_centered"] + \
                 [f"C({v})" for v in demographic_categoricals] + \
                 personality_vars

    # Filter predictors that actually exist in the dataframe
    final_predictors = []
    for p in predictors:
        col_name = p.replace('C(', '').replace(')', '')
        if col_name in model_df.columns and model_df[col_name].nunique() > 1:
            final_predictors.append(p)
        elif col_name not in model_df.columns and col_name in [v + '_centered' for v in continuous_vars]:
            final_predictors.append(p)
        elif col_name not in model_df.columns and not col_name.startswith('C('):
            final_predictors.append(p)

    formula = f"{target_var} ~ {' + '.join(final_predictors)}"

    print(f"Sample size: {len(model_df)} | Unique participants: {model_df['persona_id'].nunique()}")
    print(f"Number of categories in each demographic variable:")
    for var in demographic_vars:
        if var in model_df.columns:
            print(f"  â€¢ {var}: {model_df[var].nunique()} categories")
    print(f"\nModel formula: {formula}")

    # Fit Mixed Model
    model = smf.mixedlm(formula, model_df, groups=model_df["persona_id"],
                        vc_formula={"topic": "0 + C(topic)"})

    try:
        result = model.fit(method='lbfgs', maxiter=1000)
    except Exception as e:
        print(f"Optimization failed with lbfgs: {e}, trying powell...")
        try:
            result = model.fit(method='powell', maxiter=1000)
        except Exception as e_powell:
            print(f"Optimization also failed with powell: {e_powell}")
            raise

    # Save results
    with open(output_filename, "w") as f:
        f.write(f"MODEL: {model_description}\n")
        f.write(f"Target Variable: {target_var}\n")
        f.write("\n" + "="*80 + "\n")
        f.write("NOTE: NO CATEGORY GROUPING APPLIED\n")
        f.write("All original ethnicity, student status, and country of birth categories are preserved\n")
        f.write("="*80 + "\n\n")

        f.write("CATEGORICAL MAPPINGS APPLIED:\n")
        f.write(f"- Gender: {gender_labels}\n")
        f.write(f"- Ethnicity: {ethnicity_labels}\n")
        f.write(f"- Employment: {employment_labels}\n")
        f.write(f"- Education: {education_labels}\n")
        f.write(f"- Country: {country_labels}\n")
        f.write(f"- Student Status: {student_labels}\n")
        f.write("\nReference categories:\n")
        for col, config in categorical_config.items():
            f.write(f"  â€¢ {col}: {config['ref']}\n")
        f.write("\n" + result.summary().as_text())
        f.write(f"\n\nTotal Observations: {len(model_df)}\n")
        f.write(f"Unique Participants: {model_df['persona_id'].nunique()}\n")

        # Add category counts for key variables
        f.write("\n" + "="*80 + "\n")
        f.write("CATEGORY COUNTS (for ungrouped variables):\n")
        f.write("="*80 + "\n")
        for var in ['ethnicity', 'country_of_birth', 'student_status']:
            if var in model_df.columns:
                f.write(f"\n{var.upper()}:\n")
                counts = model_df[var].value_counts()
                for cat, count in counts.items():
                    f.write(f"  {cat}: {count} ({count/len(model_df)*100:.1f}%)\n")

    print(f"âœ“ Results saved to: {output_filename}")

    return result

