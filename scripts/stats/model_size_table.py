"""Render the model-size LaTeX table from the CSV that model_size wrote.

Nothing is computed here, so reformatting is instant. The expensive half --
bootstrap, permutation tests, complete-case assembly -- lives in
:mod:`scripts.stats.model_size` and is paid once:

    python -m scripts.stats.model_size          # minutes, writes model_size.csv
    python -m scripts.stats.model_size_table    # instant, writes model_size.tex

The CSV carries the run-level facts (n, replicates, seed, what was excluded) on
every row, so the caption below cannot end up describing a different run than
the numbers above it.

Rows are grouped by model family and, within a family, ordered by ACTIVE
parameters -- compute per token, not stored weights. That ordering is the point
of the table: it is what puts a sparse 35B-A3B next to a dense 4B, which is
where its accuracy actually sits.

    python -m scripts.stats.model_size_table --csv path/to/other.csv
    python -m scripts.stats.model_size_table --sort total
"""

import argparse

import pandas as pd

from belief_update_sim.config import STATS_OUTPUT_DIR, ensure_output_dirs

from scripts.stats.model_size import ALPHA, CSV_PATH, p_text

TEX_PATH = STATS_OUTPUT_DIR / "model_size.tex"

# Rendered instead of the family name in the group header, where the raw
# directory name is not what a reader should see.
FAMILY_LABELS = {}


def display_name(name):
    """A model or family name as the paper prints it: first letter capitalised,
    so the checkpoint's 'gemma-4-E2B-it' reads 'Gemma-4-E2B-it' beside Qwen."""
    return name[:1].upper() + name[1:]


def tex(text):
    """Escape a literal string for LaTeX text mode."""
    out = text.replace("\\", r"\textbackslash{}")
    for char in ("_", "%", "&", "#", "$", "{", "}", "~", "^"):
        out = out.replace(char, "\\" + char)
    return out


def size_text(row):
    """The size cell: active parameters, with the stored total where it differs.

    They differ for two unrelated reasons and the cell does not pretend
    otherwise -- it shows both numbers and lets the caption explain. For a
    dense model there is only one number to show.
    """
    active, total = row["params_active_b"], row["params_total_b"]
    active_s = f"{active:g}"
    if pd.isna(total) or abs(total - active) < 0.05:
        return active_s
    return f"{active_s} / {total:.0f}" if total >= 10 else f"{active_s} / {total:.1f}"


def render(table, sort="active", ci="stacked", font="small", decimals=3,
           family_headers=False, alpha=ALPHA):
    """The booktabs table, as a string.

    The $p$ column is the permutation test's own two-sided p, uncorrected.
    Significance is marked by setting p in bold when it falls below the
    Bonferroni threshold alpha / (number of models); the printed number itself
    is never adjusted. The reference baselines in the CSV are not rendered.
    """
    for column in ("source", "family", "mae", "p", "delta_lo",
                   "n_obs", "n_boot", "n_resamples"):
        if column not in table.columns:
            raise ValueError(f"{column!r} missing from the results CSV; "
                             "regenerate it with scripts.stats.model_size")

    models = table[~table["is_baseline"].astype(bool)]
    if models.empty:
        raise ValueError("the results CSV holds no models")
    threshold = alpha / len(models)

    ceilings = set(models["max_tries"].dropna().astype(int))
    if len(ceilings) != 1:
        raise ValueError(
            f"models in the sweep were given different retry budgets ({sorted(ceilings)}); "
            "one column cannot report 'used every retry' across them"
        )
    max_tries = ceilings.pop()

    meta = table.iloc[0]
    # An empty EXCLUDED writes an empty CSV field, which pandas reads back as
    # NaN -- and NaN is truthy, so `x or ""` keeps it and str() makes it the
    # word "nan". That reached the caption as "run unfinished: nan".
    excluded = ([] if pd.isna(meta["excluded"])
                else [name for name in str(meta["excluded"]).split(";") if name])
    sort_column = {"active": "params_active_b", "total": "params_total_b"}[sort]

    n_columns = 8

    lines = []
    out = lines.append
    out(r"% Generated by scripts.stats.model_size_table -- do not edit by hand.")
    out(r"% Regenerate:  python -m scripts.stats.model_size_table")
    out(r"% Requires \usepackage{booktabs}")
    out(r"\begin{table}[t]")
    out(r"\centering")
    out(r"\caption{" + caption(meta, models, max_tries, excluded, sort, alpha)
        + "}")
    out(r"\label{tab:model-size}")
    if font != "normal":
        out("\\" + font)
    # Estimate columns are right-aligned; stacked intervals sit in the same
    # column, so they are right-aligned too and the brackets line up.
    out(r"\begin{tabular}{lrrrrrrr}")
    out(r"\toprule")
    ci_head = "" if ci == "stacked" else r" [95\% CI]"
    out(r"Model & Size (B) & Valid & $n_{\mathrm{tries}}{=}" + str(max_tries)
        + r"$ & MAE" + ci_head + r" & Rank & $\Delta$" + ci_head + r" & $p$ \\")
    out(r"\midrule")

    families = list(dict.fromkeys(models["family"]))
    for i, name in enumerate(families):
        if i:
            out(r"\addlinespace")
            out(r"\midrule")
            out(r"\addlinespace")
        if family_headers:
            out(r"\multicolumn{" + str(n_columns) + r"}{l}{\textit{"
                + tex(FAMILY_LABELS.get(name, display_name(name))) + r"}} \\")
        group = models[models["family"] == name].sort_values(
            [sort_column, "params_total_b", "source"])
        for _, row in group.iterrows():
            # The family prefix may only be dropped when a header carries it.
            # Without one, "2B" alone would not say whose 2B it is.
            lines.extend(model_rows(
                row, ci=ci, decimals=decimals, threshold=threshold,
                label=short_label(row["source"], name) if family_headers
                else display_name(row["source"])))

    out(r"\bottomrule")
    out(r"\end{tabular}")
    if font != "normal":
        out(r"\normalsize")
    out(r"\end{table}")
    return "\n".join(lines) + "\n"


def short_label(source, family):
    """Drop the family prefix: the group header above the row already says it.

    'gemma-4-26B-A4B-it' under a 'gemma-4' heading becomes '26B-A4B-it', which
    is eleven characters off the widest column in the table and loses nothing a
    reader can see.
    """
    prefix = f"{family}-"
    return source[len(prefix):] if source.startswith(prefix) else source


def model_rows(row, ci="stacked", decimals=3, label=None, threshold=None):
    """The LaTeX lines for one model: one, or two when the CIs are stacked.

    Stacked puts each interval on a second line beneath its estimate. That is
    not only cosmetic: inline, a column is as wide as "1.0887 [1.0266, 1.1507]",
    and the two interval columns alone overrun a one-column page, pushing $p$
    off the edge. Stacked, each is only as wide as its interval.

    `threshold` is the Bonferroni-corrected level; a raw p below it is set in
    bold. The comparison is on the unrounded p, not on the printed digits.
    """
    label = tex(str(label if label is not None else row["source"]))
    size = size_text(row)
    valid = f"{100 * row['valid_share']:.1f}" + r"\%"
    tries = f"{100 * row['tries_share']:.1f}" + r"\%"
    rank = f"{int(row['rank'])}"

    p_value = p_text(row["p"])
    if threshold is not None and row["p"] < threshold:
        p_value = r"\mathbf{" + p_value + "}"
    p_cells = [f"${p_value}$"]

    # Three decimals by default. The intervals are ~0.06 wide, so a fourth
    # decimal is below the resolution of the estimate as well as being two
    # characters of table width per number.
    d = decimals
    mae, delta = f"{row['mae']:.{d}f}", f"{row['delta']:+.{d}f}"
    mae_ci = f"[{row['mae_lo']:.{d}f}, {row['mae_hi']:.{d}f}]"
    delta_ci = f"[{row['delta_lo']:+.{d}f}, {row['delta_hi']:+.{d}f}]"

    if ci == "inline":
        return [" & ".join([label, size, valid, tries, f"{mae} {mae_ci}", rank,
                            f"{delta} {delta_ci}", *p_cells]) + r" \\"]

    def small(text):
        # Braces scope the size change to this cell. str.format is no use here:
        # the LaTeX braces are not format fields.
        return r"{\footnotesize " + text + "}"

    return [
        " & ".join([label, size, valid, tries, mae, rank, delta, *p_cells]) + r" \\",
        " & ".join(["", "", "", "", small(mae_ci), "",
                    small(delta_ci), *[""] * len(p_cells)]) + r" \\",
    ]


def caption(meta, models, max_tries, excluded, sort, alpha=ALPHA):
    sparse = models[models["is_sparse"].astype("boolean").fillna(False)]
    parts = [
        r"Fidelity of simulated belief updates by model size, grouped by family "
        r"and ordered by " + ("active" if sort == "active" else "total")
        + r" parameters. $\Delta$ is the mean paired difference in final stance "
        r"(human $-$ model); MAE is its absolute counterpart and is what the "
        r"models are ranked on. Both are on the normalised 5-point scale, over "
        f"{int(meta['n_obs'])} persona-topic cases from "
        f"{int(meta['n_participants'])} participants on which every model "
        r"produced a parseable response.",
    ]
    if not sparse.empty:
        parts.append(
            r"\textit{Size} gives active parameters per token, with stored "
            r"parameters after a slash where the two differ: for the "
            r"mixture-of-experts models because most experts are idle, and for "
            r"Gemma's \mbox{E-}named models because per-layer embeddings are not "
            r"resident on the accelerator."
        )
    parts.append(
        r"\textit{Valid} is the share of all "
        f"{int(meta['valid_total'])} cases that model parsed and "
        r"$n_{\mathrm{tries}}{=}" + str(max_tries) + r"$ the share that needed "
        r"every one of its " + str(max_tries) + r" allowed attempts; both are "
        r"over all cases, before the complete-case intersection above was taken, "
        r"so a low figure means that row rests on a subset the model selected by "
        r"succeeding on it."
    )
    parts.append(
        r"Each 95\% CI is a cluster bootstrap percentile interval for the "
        r"statistic beside it: the "
        f"{int(meta['n_participants'])} participants are resampled with "
        r"replacement, each carrying all of their topics, the statistic is "
        r"recomputed on every resampled dataset, and the bounds are the "
        r"$2.5$th and $97.5$th percentiles of those "
        + f"{int(meta['n_boot']):,}".replace(",", r"{,}") + r" values."
    )
    parts.append(
        r"$p$ tests $\Delta = 0$ by a two-sided paired sign-flip permutation "
        r"test over " + f"{int(meta['n_resamples']):,}".replace(",", r"{,}")
        + r" resamples; it is the test of the paired signed difference, so it "
        r"belongs with $\Delta$ and not with the MAE. $p$ is reported "
        r"uncorrected; values in bold are significant at "
        f"$\\alpha = {alpha:g}$ after Bonferroni correction across the "
        f"{len(models)} models ($p < {alpha:g}/{len(models)}$)."
    )
    if excluded:
        parts.append("Excluded, run unfinished: "
                     + ", ".join(tex(name) for name in excluded) + ".")
    return " ".join(parts)


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--csv", default=CSV_PATH, type=str,
                        help="results CSV written by scripts.stats.model_size")
    parser.add_argument("--out", default=TEX_PATH, type=str)
    parser.add_argument("--sort", choices=("active", "total"), default="active",
                        help="order within a family (default: active parameters)")
    parser.add_argument("--alpha", type=float, default=ALPHA,
                        help="family-wise level for the Bonferroni bolding "
                             f"(default: {ALPHA})")
    parser.add_argument("--ci", choices=("stacked", "inline"), default="stacked",
                        help="stacked puts each interval on a line under its "
                             "estimate, which is what makes the table fit a "
                             "one-column page (default: stacked)")
    parser.add_argument("--font", choices=("normal", "small", "footnotesize"),
                        default="small", help="table body size (default: small)")
    parser.add_argument("--decimals", type=int, default=3,
                        help="decimal places for MAE and Delta (default: 3)")
    parser.add_argument("--family-headers", action="store_true",
                        help="add a heading row per model family, and shorten "
                             "the row labels by dropping the family prefix")
    args = parser.parse_args()

    try:
        table = pd.read_csv(args.csv)
    except FileNotFoundError:
        raise SystemExit(
            f"no results CSV at {args.csv}. Compute it first:\n"
            f"    python -m scripts.stats.model_size"
        )

    text = render(table, args.sort, args.ci, args.font, args.decimals,
                  args.family_headers, args.alpha)
    print(text)
    ensure_output_dirs()
    with open(args.out, "w", encoding="utf-8") as handle:
        handle.write(text)
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
